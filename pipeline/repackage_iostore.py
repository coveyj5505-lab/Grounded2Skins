#!/usr/bin/env python3
"""Pack a new unsigned IoStore with a matching TOC/Header/chunk-key identity."""
import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
from pathlib import Path


def repackage(raw, pak, work, retoc, mod_name="zMeshTest_P"):
    assert mod_name.endswith("_P") and all(c.isalnum() or c in "_-" for c in mod_name)
    work.mkdir(parents=True, exist_ok=False)
    logs = work / 'logs'
    logs.mkdir()
    commands = []

    def run(label, *args):
        command = [str(retoc), *map(str, args)]
        with (logs / (label + '.log')).open('w') as stream:
            status = subprocess.run(command, cwd=work, env=dict(os.environ, RAYON_NUM_THREADS='4'),
                                    stdout=stream, stderr=subprocess.STDOUT)
        commands.append({'label': label, 'command': command, 'exit_code': status.returncode})
        (work / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        status.check_returncode()

    # Ask the same writer for its filename-derived ID; no hash reimplementation.
    probe = work / 'identity-probe'
    (probe / 'raw/chunks').mkdir(parents=True)
    manifest = json.loads((raw / 'manifest.json').read_text())
    (probe / 'raw/manifest.json').write_text(json.dumps(dict(manifest, chunk_paths={})))
    run('identity-probe', 'pack-raw', probe / 'raw', probe / (mod_name + '.utoc'))
    probe_toc = (probe / (mod_name + '.utoc')).read_bytes()
    assert probe_toc[:16] == b'-==--==--==--==-'
    assert probe_toc[16] == 8 and not (probe_toc[80] & 6)
    new_id = probe_toc[56:64]
    staged = work / 'raw'
    shutil.copytree(raw, staged)
    headers = [p for p in (staged / 'chunks').iterdir() if p.name.endswith('00000006')]
    assert len(headers) == 1
    old = headers[0]
    original = old.read_bytes()
    assert original[:4] == bytes.fromhex('6e436f49') and struct.unpack_from('<I', original, 4)[0] == 5
    old_id = original[8:16]
    assert old.name == old_id.hex() + '00000006' and old_id != new_id
    assert old.name not in manifest['chunk_paths'], 'Expected unindexed ContainerHeader'
    data = original[:8] + new_id + original[16:]
    new_header = staged / 'chunks' / (new_id.hex() + '00000006')
    assert not new_header.exists()
    new_header.write_bytes(data)
    old.unlink()  # generated staging copy only
    output = work / 'mod'
    output.mkdir()
    toc = output / (mod_name + '.utoc')
    run('pack', 'pack-raw', staged, toc)
    assert toc.read_bytes()[56:64] == new_id
    shutil.copyfile(pak, toc.with_suffix('.pak'))
    run('verify', 'verify', toc)
    run('info', 'info', toc)
    package_count = sum(path.endswith('.uasset') for path in manifest['chunk_paths'].values())
    chunk_count = len(list((staged / 'chunks').iterdir()))
    assert f'packages: {package_count}' in (logs / 'info.log').read_text()
    run('list', 'list', toc, '--hash', '--size', '--path', '--store')
    unpacked = work / 'unpacked'
    run('unpack', 'unpack-raw', toc, unpacked)
    hashes = lambda folder: {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                             for p in (folder / 'chunks').iterdir()}
    assert hashes(staged) == hashes(unpacked)
    assert len(hashes(unpacked)) == chunk_count
    assert json.loads((unpacked / 'manifest.json').read_text()) == manifest
    assert (unpacked / 'chunks' / new_header.name).read_bytes()[8:16] == new_id
    result = {'mod_name': mod_name, 'toc_version': 8,
              'old_container_id_le_hex': old_id.hex(), 'new_container_id_le_hex': new_id.hex(),
              'new_container_id_decimal': int.from_bytes(new_id, 'little'),
              'toc_header_chunk_key_and_header_identity_match': True,
              'header_only_changed_id_bytes': data[:8] == original[:8] and data[16:] == original[16:],
              'packages_recognized': package_count, 'chunks_verified': chunk_count,
              'all_reextracted_chunk_hashes_match_staged': True,
              'all_asset_paths_unchanged': True,
              'compression': 'None; 64 KiB blocks, offsets and BLAKE3-160 hashes generated by retoc',
              'signature': 'unsigned and unencrypted, as input',
              'in_game_test': 'NOT RUN', 'files': []}
    for path in sorted(output.iterdir()):
        result['files'].append({'name': path.name, 'bytes': path.stat().st_size,
                                'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    (work / 'repackage-validation.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('raw', type=Path)
    p.add_argument('empty_original_pak', type=Path)
    p.add_argument('work', type=Path)
    p.add_argument('--retoc', type=Path, default=Path('/workspace/mod-work/bin/retoc'))
    p.add_argument('--mod-name', default='zMeshTest_P')
    a = p.parse_args()
    repackage(a.raw.resolve(), a.empty_original_pak.resolve(), a.work.resolve(), a.retoc.resolve(), a.mod_name)
